"""Generate ytcore/db/migrations/002_transitions_seed.sql from ytcore/workflow/states.py.

Usage:
    python ytcore/tools/gen_transitions_sql.py          # write the file
    python ytcore/tools/gen_transitions_sql.py --check  # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ytcore.workflow.states import (  # noqa: E402
    APPROVAL_GATED_STATES,
    TERMINAL_STATES,
    JobState,
    sorted_transitions,
)

OUTPUT = ROOT / "ytcore" / "db" / "migrations" / "002_transitions_seed.sql"


def render() -> str:
    lines = [
        "-- GENERATED by ytcore/tools/gen_transitions_sql.py from ytcore/workflow/states.py.",
        "-- Do not edit by hand. CI fails if this file drifts from the generator output.",
        "BEGIN;",
        "",
        "INSERT INTO job_states (state, is_terminal, requires_approval) VALUES",
    ]
    rows = [
        f"    ('{s.value}', {str(s in TERMINAL_STATES).lower()}, "
        f"{str(s in APPROVAL_GATED_STATES).lower()})"
        for s in JobState
    ]
    lines.append(",\n".join(rows) + ";")
    lines += ["", "INSERT INTO job_state_transitions (from_state, to_state) VALUES"]
    pairs = [f"    ('{s.value}', '{d.value}')" for s, d in sorted_transitions()]
    lines.append(",\n".join(pairs) + ";")
    lines += ["", "COMMIT;", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the SQL file is stale")
    args = parser.parse_args(argv)
    expected = render()
    if args.check:
        actual = OUTPUT.read_text() if OUTPUT.exists() else ""
        if actual != expected:
            print(
                f"{OUTPUT.relative_to(ROOT)} is out of date with states.py; "
                "run `python ytcore/tools/gen_transitions_sql.py`.",
                file=sys.stderr,
            )
            return 1
        print("transitions seed is up to date")
        return 0
    OUTPUT.write_text(expected)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
